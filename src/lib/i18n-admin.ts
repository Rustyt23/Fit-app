export const ADMIN_DICTIONARIES: Record<Lang, Record<AKey, string>> = { en, hi };

export type AT = (key: AKey, vars?: Record<string, string | number>) => string;

/** Admin text in the admin's own language (English if unknown). */
export function adminText(lang: Lang | string | undefined): AT {
  const dict = ADMIN_DICTIONARIES[lang === "hi" ? "hi" : "en"];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
